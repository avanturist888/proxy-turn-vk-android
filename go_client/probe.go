package main

import (
	"sync"
	"time"
)

// pathProbe — широковещательный запрос «проверьте путь прямо сейчас».
//
// Смену сети Android замечает мгновенно, а клиент узнавал о ней только по
// тишине — до sessionSilenceTimeout (35с) простоя, потому что отличить
// «сеть сменилась, но сессия выжила» от «сеть сменилась, сессия умерла»
// пассивным наблюдением нельзя: свежий pong в обоих случаях выглядит
// одинаково, пока не устареет.
//
// Проба разрывает эту неопределённость активно: сессии немедленно шлют
// keepalive и ждут ответа несколько секунд. Ответившие остаются жить —
// в отличие от RECONNECT (epoch.go), который рвёт всё подряд, включая
// уцелевшие сессии.
type pathProbe struct {
	mu sync.Mutex
	ch chan struct{}
}

func newPathProbe() *pathProbe {
	return &pathProbe{ch: make(chan struct{})}
}

// wait возвращает канал, который закроется на следующем request.
// Подписываться нужно перед ожиданием и заново после каждого срабатывания.
func (p *pathProbe) wait() <-chan struct{} {
	p.mu.Lock()
	defer p.mu.Unlock()
	return p.ch
}

// request будит все сессии, подписанные на текущий канал.
func (p *pathProbe) request() {
	p.mu.Lock()
	defer p.mu.Unlock()
	close(p.ch)
	p.ch = make(chan struct{})
}

// sessionProbeTimeout — сколько ждать ответ на пробную отправку keepalive,
// прежде чем считать путь мёртвым. Запас на мобильную сеть с плохим RTT:
// цена ошибки — лишнее пересоздание сессии, но слишком щедрый порог
// возвращает нас к медленному детекту, ради ускорения которого проба и
// существует.
const sessionProbeTimeout = 6 * time.Second
